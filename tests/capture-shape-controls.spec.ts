test('shape popup and combined glyph fit small screens at each toolbar scale and DPI', async ({ browser }) => {
  for (const ratio of [1, 1.25, 1.5, 2]) {
    const context = await browser.newContext({ viewport: { width: 800, height: 720 }, deviceScaleFactor: ratio })
    const page = await context.newPage()
    for (const scale of [80, 100, 150, 200]) {
      await page.goto(`/?capture-lab=1&scale=${scale}`); await expect(page.locator('.jt-chrome')).toBeVisible()
      await page.mouse.move(180, 100); await page.mouse.down(); await page.mouse.move(780, 660); await page.mouse.up()
      const trigger = page.getByRole('button', { name: shapeLabel, exact: true }); await trigger.click()
      const menu = page.getByRole('menu', { name: '选择形状' }); await expect(menu).toBeVisible()
      const box = await menu.boundingBox(); expect(box).not.toBeNull()
      expect(box?.x).toBeGreaterThanOrEqual(0); expect(box && box.x + box.width).toBeLessThanOrEqual(800)
      expect(box?.y).toBeGreaterThanOrEqual(0); expect(box && box.y + box.height).toBeLessThanOrEqual(720)
      const glyphs = await trigger.evaluate(element => [...element.querySelectorAll('svg')].map(svg => { const r = svg.getBoundingClientRect(), b = element.getBoundingClientRect(); return r.x >= b.x && r.right <= b.right && r.y >= b.y && r.bottom <= b.bottom }))
      expect(glyphs).toEqual([true, true])
      await page.getByRole('menuitemradio', { name: '椭圆（Shift 正圆）', exact: true }).click()
      await expect(trigger).toHaveAttribute('aria-pressed', 'true')
      if (ratio === 1.5 && scale === 150) await page.screenshot({ path: '.task/capture-shape-toolbar-dpi150.png' })
    }
    await context.close()
  }
})

